/**
 * RC2 issue 3 — tested-build inventory + artifact-integrity chain.
 *
 * The old `verify-packaged.mjs` compared the ZIP with the build DIRECTORY
 * after `wxt zip` had rebuilt it — proving the zip matched its packaging
 * build, not the build the browser tests exercised. This tool closes the
 * gap with an explicit inventory lifecycle:
 *
 *   capture <outDirName> <target>   IMMUTABLY snapshot the distributable
 *                                   build (path + sha256 + size) into
 *                                   .agents/block-the-slop-v7/inventory/
 *   check-test <outDirName> <target>  FAIL if the build dir no longer
 *                                   matches the captured inventory (detects
 *                                   drift between build and browser tests)
 *   check-zip <zipName> <outDirName> <target>
 *                                   Compare every ZIP entry against the
 *                                   captured inventory: missing / extra /
 *                                   changed files fail. Unsafe paths
 *                                   (absolute, .., backslash) and duplicate
 *                                   entries are rejected.
 *
 * The inventory is NEVER regenerated by check commands. Cross-platform:
 * pure Node (no unzip), works on Windows and POSIX. Exits nonzero with a
 * clear list on any mismatch.
 *
 * CLI:
 *   node scripts/artifact-inventory.mjs capture chrome-mv3 chrome
 *   node scripts/artifact-inventory.mjs check-test chrome-mv3 chrome
 *   node scripts/artifact-inventory.mjs check-zip block-the-slop-1.0.0-chrome.zip chrome-mv3 chrome
 */
import { createHash } from 'node:crypto';
import { inflateRawSync } from 'node:zlib';
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, normalize, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const INVENTORY_DIR = join(root, '.agents', 'block-the-slop-v7', 'inventory');
/** Files present in .output but never distributed (packaging excludes them). */
const NON_DISTRIBUTABLE = new Set(['manifest.json.map']);

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

function listFiles(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) listFiles(full, out);
    else out.push(full);
  }
  return out;
}

function posix(p) {
  return p.split('\\').join('/');
}

/** Inventory of the CURRENT build dir: { "rel/path": {sha256, bytes} }. */
function inventoryFromDir(buildDir) {
  const map = {};
  for (const full of listFiles(buildDir)) {
    const rel = posix(relative(buildDir, full));
    if (NON_DISTRIBUTABLE.has(rel)) continue;
    const buf = readFileSync(full);
    map[rel] = { sha256: sha256(buf), bytes: buf.length };
  }
  return map;
}

function inventoryPath(target) {
  return join(INVENTORY_DIR, `tested-build-${target}.json`);
}

function readInventory(target) {
  const p = inventoryPath(target);
  if (!existsSync(p)) {
    return {
      ok: false,
      error: `missing inventory for target ${target}: ${posix(relative(root, p))} (run the capture command first; never regenerate it after a mismatch)`,
    };
  }
  try {
    const data = JSON.parse(readFileSync(p, 'utf8'));
    if (data.target !== target || typeof data.files !== 'object' || data.files === null) {
      return { ok: false, error: `inventory for ${target} is malformed or for another target` };
    }
    return { ok: true, data };
  } catch (error) {
    return {
      ok: false,
      error: `inventory unreadable: ${error instanceof Error ? error.message : error}`,
    };
  }
}

function diffInventory(expected, actual, whatExpected) {
  const problems = [];
  for (const [rel, meta] of Object.entries(expected)) {
    const got = actual[rel];
    if (got === undefined) {
      problems.push(`MISSING from ${whatExpected}: ${rel}`);
    } else if (got.sha256 !== meta.sha256) {
      problems.push(`CHANGED in ${whatExpected}: ${rel}`);
    }
  }
  for (const rel of Object.keys(actual)) {
    if (expected[rel] === undefined) problems.push(`EXTRA in ${whatExpected}: ${rel}`);
  }
  return problems;
}

// ---- minimal ZIP central-directory reader (pure Node) ----------------------

/** Parse the End Of Central Directory record. */
function findEocd(buf) {
  for (let i = buf.length - 22; i >= Math.max(0, buf.length - 22 - 65_536); i--) {
    if (buf.readUInt32LE(i) === 0x06054b50) return i;
  }
  return -1;
}

/**
 * Extract every entry's (name, duplicate detection, content) from a ZIP.
 * Rejects unsafe names (absolute, `..`, backslash) and duplicate entries.
 * Returns { entries: Map<name, Buffer>, problems: string[] }.
 */
export function readZipEntries(buf) {
  const problems = [];
  const eocd = findEocd(buf);
  if (eocd === -1) {
    return { entries: new Map(), problems: ['not a ZIP file (no EOCD record)'] };
  }
  const count = buf.readUInt16LE(eocd + 10);
  let offset = buf.readUInt32LE(eocd + 16);
  const entries = new Map();
  for (let i = 0; i < count; i++) {
    if (buf.readUInt32LE(offset) !== 0x02014b50) {
      problems.push(`bad central directory entry ${i}`);
      break;
    }
    const method = buf.readUInt16LE(offset + 10);
    const compressedSize = buf.readUInt32LE(offset + 20);
    const nameLen = buf.readUInt16LE(offset + 28);
    const extraLen = buf.readUInt16LE(offset + 30);
    const commentLen = buf.readUInt16LE(offset + 32);
    const localOffset = buf.readUInt32LE(offset + 42);
    const name = buf.toString('utf8', offset + 46, offset + 46 + nameLen);
    // Unsafe path check (store zips use forward slashes; reject the rest).
    if (name.includes('\\')) {
      problems.push(`unsafe entry (backslash): ${name}`);
    } else if (name.startsWith('/') || /^[A-Za-z]:/.test(name)) {
      problems.push(`unsafe entry (absolute): ${name}`);
    } else {
      const normalized = normalize(name);
      if (normalized.startsWith('..') || normalized.includes('/../')) {
        problems.push(`unsafe entry (traversal): ${name}`);
      } else if (entries.has(name)) {
        problems.push(`duplicate entry: ${name}`);
      }
    }
    // Content: directory entries have no stored bytes. METHOD 0 (store) and
    // METHOD 8 (deflate, what `wxt zip`/zip defaults produce) are decoded;
    // anything else cannot be compared byte-for-byte and is rejected.
    if (!name.endsWith('/')) {
      const localNameLen = buf.readUInt16LE(localOffset + 26);
      const localExtraLen = buf.readUInt16LE(localOffset + 28);
      const dataStart = localOffset + 30 + localNameLen + localExtraLen;
      const raw = buf.subarray(dataStart, dataStart + compressedSize);
      if (method === 0) {
        entries.set(name, raw);
      } else if (method === 8) {
        try {
          entries.set(name, inflateRawSync(raw));
        } catch {
          problems.push(`corrupt deflate stream in entry: ${name}`);
        }
      } else {
        problems.push(`unsupported compression (method ${method}) in entry: ${name}`);
      }
    }
    offset += 46 + nameLen + extraLen + commentLen;
  }
  return { entries, problems };
}

// ---- commands ---------------------------------------------------------------

function capture(outDirName, target) {
  const buildDir = join(root, '.output', outDirName);
  if (!existsSync(buildDir)) {
    console.error(`✗ build dir missing: .output/${outDirName}`);
    process.exit(1);
  }
  const files = inventoryFromDir(buildDir);
  const payload = {
    schema: 1,
    capturedAt: new Date().toISOString(),
    target,
    buildDir: outDirName,
    fileCount: Object.keys(files).length,
    files,
  };
  mkdirSync(INVENTORY_DIR, { recursive: true });
  writeFileSync(inventoryPath(target), JSON.stringify(payload, null, 2));
  console.log(
    `✓ captured tested-build inventory for ${target}: ${payload.fileCount} files → .agents/block-the-slop-v7/inventory/tested-build-${target}.json`,
  );
}

function checkTest(outDirName, target) {
  const inv = readInventory(target);
  if (!inv.ok) {
    console.error(`✗ ${inv.error}`);
    process.exit(1);
  }
  const buildDir = join(root, '.output', outDirName);
  if (!existsSync(buildDir)) {
    console.error(`✗ build dir missing: .output/${outDirName}`);
    process.exit(1);
  }
  const current = inventoryFromDir(buildDir);
  const problems = diffInventory(inv.data.files, current, `tested build (${outDirName})`);
  if (problems.length > 0) {
    console.error(`✗ tested build drifted from the captured inventory (target ${target}):`);
    for (const p of problems) console.error(`  - ${p}`);
    process.exit(1);
  }
  console.log(
    `✓ tested build still matches the captured inventory (${inv.data.fileCount} files, target ${target})`,
  );
}

function checkZip(zipName, outDirName, target) {
  const inv = readInventory(target);
  if (!inv.ok) {
    console.error(`✗ ${inv.error}`);
    process.exit(1);
  }
  const zipPath = zipName.includes('/') ? zipName : join(root, '.output', zipName);
  if (!existsSync(zipPath)) {
    console.error(`✗ missing zip: ${zipPath}`);
    process.exit(1);
  }
  const { entries, problems } = readZipEntries(readFileSync(zipPath));
  if (problems.length > 0) {
    console.error(`✗ zip ${zipName} rejected:`);
    for (const p of problems) console.error(`  - ${p}`);
    process.exit(1);
  }
  const actual = {};
  for (const [name, content] of entries) {
    actual[name] = { sha256: sha256(content), bytes: content.length };
  }
  const mismatches = diffInventory(inv.data.files, actual, `zip ${zipName}`);
  if (mismatches.length > 0) {
    console.error(
      `✗ packaged zip ${zipName} does NOT match the tested-build inventory (target ${target}):`,
    );
    for (const m of mismatches) console.error(`  - ${m}`);
    process.exit(1);
  }
  console.log(
    `✓ packaged zip matches the tested-build inventory byte-for-byte: ${zipName} (${inv.data.fileCount} files, target ${target})`,
  );
}

// ---- CLI --------------------------------------------------------------------
// Run the CLI only when invoked DIRECTLY (not when imported by tests): the
// scenario suite imports the sandbox copy of this file to exercise readZipEntries.
import { pathToFileURL } from 'node:url';
const invokedDirectly =
  process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;
if (invokedDirectly) {
  const [cmd, a, b, c] = process.argv.slice(2);
  if (cmd === 'capture' && a && b) capture(a, b);
  else if (cmd === 'check-test' && a && b) checkTest(a, b);
  else if (cmd === 'check-zip' && a && b && c) checkZip(a, b, c);
  else {
    console.error('usage: artifact-inventory.mjs capture|check-test|check-zip <args> (see header)');
    process.exit(2);
  }
}
